"""Blender --background --factory-startup --python Tools/UI/export_arrow.py.
Project the supplied arrow's upper cap into a small Canvas mesh; no runtime FBX import.
"""
from pathlib import Path
import bpy

root = Path(__file__).resolve().parents[2]
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.fbx(filepath=str(root / 'Tools/UI/Pointer Arrow.fbx'))
mesh = next(obj for obj in bpy.context.scene.objects if obj.type == 'MESH')
points = [mesh.matrix_world @ v.co for v in mesh.data.vertices]
top = max(p.z for p in points)
middle_x = (min(p.x for p in points) + max(p.x for p in points)) / 2
length = max(p.x for p in points) - min(p.x for p in points)
mesh.data.calc_loop_triangles()
triangles = []
for tri in mesh.data.loop_triangles:
    if all(abs(points[i].z - top) < 0.0001 for i in tri.vertices):
        # Source points along -X. Output points up (-Y), centred and 64 HUD units long.
        triangles.append([(points[i].y * 64 / length,
                           (points[i].x - middle_x) * 64 / length) for i in tri.vertices])
assert triangles, 'Missing upper arrow cap'
output = '// Generated by Tools/UI/export_arrow.py from the supplied Pointer Arrow.fbx.\n'
output += 'static constexpr float GoalArrowTriangles[][6]={\n'
for tri in triangles:
    output += ' {' + ','.join(f'{v:.6f}f' for point in tri for v in point) + '},\n'
output += '};\n'
(root / 'Source/CiazParking/GoalArrow.inl').write_text(output)
print(f'Exported {len(triangles)} arrow triangles')
